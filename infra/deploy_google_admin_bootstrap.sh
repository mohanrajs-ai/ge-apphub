#!/usr/bin/env bash
# ==============================================================================
# Google Admin & Cloud Identity Bootstrap Orchestrator (Phase 0B Automation)
# ==============================================================================
# Automates Phase 0B (Google Admin Console / admin.google.com setup):
#   [Step 0B.1a — Auto-Discovery of Cloud Identity Customer ID & Root Org Unit]
#     1. Queries 'gcloud organizations list' and Admin SDK Directory API
#        (/admin/directory/v1/customers/my_customer) to automatically resolve:
#          - GCP_ORG_ID
#          - CLOUD_IDENTITY_CUSTOMER_ID (customers/C0xxxxxxx)
#          - SAML_TARGET_ORG_UNIT (orgUnits/03ph8a2z...)
#   [Step 0B.1b — Automated Domain Registration, Cloud DNS TXT & Verification]
#     2. Checks / registers <customer_domain> in Google Admin Directory API
#        (/admin/directory/v1/customer/<id>/domains)
#     3. Requests the 'google-site-verification=...' TXT token via Google Site
#        Verification API (https://www.googleapis.com/siteVerification/v1/token)
#     4. Automatically provisions the TXT verification record in Cloud DNS
#        (when --dns-zone-name is provided) and triggers automated verification
#        via POST /siteVerification/v1/webResource?verificationMethod=DNS_TXT
#   [Step 0B.2 — Admin API Verification & Inbound SAML SSO Profile Assignment]
#     5. Enables admin.googleapis.com, cloudidentity.googleapis.com,
#        siteverification.googleapis.com, and dns.googleapis.com
#     6. Verifies Admin API access (Groups & Directory APIs)
#     7. Creates/updates the Cloud Identity Inbound SAML SSO Profile, uploads
#        configs/<customer>-entra-saml.cer (if generated by Step 0A.2), and
#        assigns SAML SSO to the discovered Root Org Unit (inboundSsoAssignments)
#     8. Auto-generates configs/<customer>-identity.env for Phase 1
#
# Usage:
#   ./deploy_google_admin_bootstrap.sh \
#     --customer-name "cymbal" \
#     --customer-domain "cymbal.com" \
#     --gcp-project-id "cymbal-ge-prod" \
#     [--entra-tenant-id "11111111-2222-3333-4444-555555555555"] \
#     [--dns-zone-name "cymbal-com-zone"] \
#     [--dns-project-id "cymbal-ge-prod"] \
#     [--tf-state-bucket "cymbal-ge-tfstate"] \
#     [--dry-run]
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIGS_DIR="${SCRIPT_DIR}/configs"
mkdir -p "${CONFIGS_DIR}"

export CLOUDSDK_METRICS_ENVIRONMENT="geapphub"

CUSTOMER_NAME="cymbal"
CUSTOMER_DOMAIN="cymbal.com"
ENTRA_SOURCE_DOMAIN=""
GCP_PROJECT_ID="cymbal-ge-prod"
GCP_REGION="us-central1"
ENTRA_TENANT_ID=""
DNS_ZONE_NAME=""
DNS_PROJECT_ID=""
TF_STATE_BUCKET=""
CLOUD_IDENTITY_CUSTOMER_ID=""
GCP_ORG_ID=""
SAML_TARGET_ORG_UNIT=""
DRY_RUN="false"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --customer-name)
      CUSTOMER_NAME="$2"
      shift 2
      ;;
    --customer-domain)
      CUSTOMER_DOMAIN="$2"
      shift 2
      ;;
    --entra-source-domain)
      ENTRA_SOURCE_DOMAIN="$2"
      shift 2
      ;;
    --gcp-project-id)
      GCP_PROJECT_ID="$2"
      shift 2
      ;;
    --gcp-region)
      GCP_REGION="$2"
      shift 2
      ;;
    --entra-tenant-id|--tenant-id)
      ENTRA_TENANT_ID="$2"
      shift 2
      ;;
    --dns-zone-name)
      DNS_ZONE_NAME="$2"
      shift 2
      ;;
    --dns-project-id)
      DNS_PROJECT_ID="$2"
      shift 2
      ;;
    --tf-state-bucket)
      TF_STATE_BUCKET="$2"
      shift 2
      ;;
    --cloud-identity-customer-id)
      CLOUD_IDENTITY_CUSTOMER_ID="$2"
      shift 2
      ;;
    --gcp-org-id)
      GCP_ORG_ID="$2"
      shift 2
      ;;
    --saml-target-org-unit)
      SAML_TARGET_ORG_UNIT="$2"
      shift 2
      ;;
    --dry-run)
      DRY_RUN="true"
      shift 1
      ;;
    *)
      echo "Unknown flag: $1"
      exit 1
      ;;
  esac
done

if [[ -z "${ENTRA_SOURCE_DOMAIN}" ]]; then
  if command -v az >/dev/null 2>&1 && az account show >/dev/null 2>&1; then
    ENTRA_SOURCE_DOMAIN="$(az rest --method GET --uri "https://graph.microsoft.com/v1.0/domains" --query "value[?isInitial].id | [0]" -o tsv 2>/dev/null || true)"
  fi
  ENTRA_SOURCE_DOMAIN="${ENTRA_SOURCE_DOMAIN:-${CUSTOMER_NAME}.onmicrosoft.com}"
fi
if [[ -z "${DNS_PROJECT_ID}" ]]; then
  DNS_PROJECT_ID="${GCP_PROJECT_ID}"
fi
if [[ -z "${TF_STATE_BUCKET}" ]]; then
  TF_STATE_BUCKET="${CUSTOMER_NAME}-ge-tfstate"
fi

CUSTOMER_UPPER="$(printf '%s' "${CUSTOMER_NAME}" | tr '[:lower:]' '[:upper:]')"
SAML_PROFILE_DISPLAY_NAME="${CUSTOMER_UPPER} Microsoft Entra ID SSO"
SAML_CERT_FILE="${CONFIGS_DIR}/${CUSTOMER_NAME}-entra-saml.cer"
IDENTITY_ENV_OUT="${CONFIGS_DIR}/${CUSTOMER_NAME}-identity.env"

echo "=================================================================="
echo " Google Admin & Cloud Identity Phase 0B Automation"
echo "------------------------------------------------------------------"
echo " Customer         : ${CUSTOMER_NAME} (${CUSTOMER_DOMAIN})"
echo " App GCP Project  : ${GCP_PROJECT_ID}"
echo " DNS GCP Project  : ${DNS_PROJECT_ID}"
echo " Cloud DNS Zone   : ${DNS_ZONE_NAME:-<auto-discover or external DNS>}"
echo " Dry-Run Mode     : ${DRY_RUN}"
echo "=================================================================="

if [[ "${DRY_RUN}" == "true" ]]; then
  echo "[DRY-RUN] [Step 0B.1a] Would enable cloudresourcemanager.googleapis.com, serviceusage.googleapis.com, admin.googleapis.com, cloudidentity.googleapis.com, siteverification.googleapis.com on '${GCP_PROJECT_ID}'"
  if [[ "${DNS_PROJECT_ID}" != "${GCP_PROJECT_ID}" || -n "${DNS_ZONE_NAME}" ]]; then
    echo "[DRY-RUN] [Step 0B.1a] Would enable dns.googleapis.com on DNS project '${DNS_PROJECT_ID}'"
  fi
  echo "[DRY-RUN] [Step 0B.1a] Would auto-discover GCP_ORG_ID, CLOUD_IDENTITY_CUSTOMER_ID (customers/C0xxxxxxx), and Root Org Unit ID (orgUnits/...) for '${CUSTOMER_DOMAIN}'"
  echo "[DRY-RUN] [Step 0B.1b] Would check/register '${CUSTOMER_DOMAIN}' via Admin SDK Domains API (/admin/directory/v1/customer/my_customer/domains)"
  echo "[DRY-RUN] [Step 0B.1b] Would request DNS_TXT token via Google Site Verification API (https://www.googleapis.com/siteVerification/v1/token)"
  if [[ -n "${DNS_ZONE_NAME}" ]]; then
    echo "[DRY-RUN] [Step 0B.1b] Would provision TXT verification record in Cloud DNS zone '${DNS_ZONE_NAME}' (${DNS_PROJECT_ID})"
  fi
  echo "[DRY-RUN] [Step 0B.1b] Would trigger automated domain verification via POST /siteVerification/v1/webResource?verificationMethod=DNS_TXT"
  echo "[DRY-RUN] [Step 0B.2]  Would verify Admin SDK Directory API & Cloud Identity Groups API readiness"
  echo "[DRY-RUN] [Step 0B.2]  Would create/update Inbound SAML SSO Profile '${SAML_PROFILE_DISPLAY_NAME}' and assign to Root Org Unit"
  echo "[DRY-RUN] [Step 0B.2]  Would write '${IDENTITY_ENV_OUT}' with all resolved IDs"
  exit 0
fi

# ------------------------------------------------------------------------------
# 1. Enable Required Google Admin, Cloud Identity, Site Verification & DNS APIs
# ------------------------------------------------------------------------------
echo "[1/6] [Step 0B.2] Enabling Google Admin SDK, Cloud Identity, Site Verification & Cloud Resource Manager APIs on '${GCP_PROJECT_ID}'..."
gcloud services enable \
  cloudresourcemanager.googleapis.com \
  serviceusage.googleapis.com \
  admin.googleapis.com \
  cloudidentity.googleapis.com \
  siteverification.googleapis.com \
  secretmanager.googleapis.com \
  --project="${GCP_PROJECT_ID}"

if [[ "${DNS_PROJECT_ID}" != "${GCP_PROJECT_ID}" || -n "${DNS_ZONE_NAME}" ]]; then
  echo "      Enabling Cloud DNS & Resource Manager APIs on DNS project '${DNS_PROJECT_ID}'..."
  gcloud services enable \
    cloudresourcemanager.googleapis.com \
    serviceusage.googleapis.com \
    dns.googleapis.com \
    --project="${DNS_PROJECT_ID}"
fi

if [[ -z "${DNS_ZONE_NAME}" ]]; then
  DNS_ZONE_NAME="$(gcloud dns managed-zones list --project="${DNS_PROJECT_ID}" --filter="dnsName=${CUSTOMER_DOMAIN}." --format="value(name)" 2>/dev/null | head -n 1 || true)"
  if [[ -n "${DNS_ZONE_NAME}" ]]; then
    echo "      Auto-discovered Cloud DNS zone '${DNS_ZONE_NAME}' for '${CUSTOMER_DOMAIN}.' in DNS project '${DNS_PROJECT_ID}'."
  fi
fi

GCP_TOKEN="$(gcloud auth print-access-token)"

# ------------------------------------------------------------------------------
# 2. Step 0B.1a: Auto-Discover GCP_ORG_ID, CLOUD_IDENTITY_CUSTOMER_ID & Root OU
# ------------------------------------------------------------------------------
echo "[2/6] [Step 0B.1a] Auto-discovering Cloud Identity Customer ID, GCP Org ID & Root Org Unit for ${CUSTOMER_DOMAIN}..."
if [[ -z "${GCP_ORG_ID}" || -z "${CLOUD_IDENTITY_CUSTOMER_ID}" ]]; then
  ORG_LINE="$(gcloud organizations list --filter="displayName:${CUSTOMER_DOMAIN}" --format="value(name,owner.directoryCustomerId)" 2>/dev/null | head -n 1 || true)"
  if [[ -z "${ORG_LINE}" ]]; then
    ORG_LINE="$(gcloud organizations list --format="value(name,owner.directoryCustomerId)" 2>/dev/null | head -n 1 || true)"
  fi
  if [[ -n "${ORG_LINE}" ]]; then
    DISCOVERED_ORG="$(echo "${ORG_LINE}" | awk '{print $1}' | sed 's|organizations/||')"
    DISCOVERED_CUST="$(echo "${ORG_LINE}" | awk '{print $2}')"
    GCP_ORG_ID="${GCP_ORG_ID:-${DISCOVERED_ORG}}"
    if [[ -n "${DISCOVERED_CUST}" && -z "${CLOUD_IDENTITY_CUSTOMER_ID}" ]]; then
      CLOUD_IDENTITY_CUSTOMER_ID="customers/${DISCOVERED_CUST#customers/}"
    fi
  fi
fi

# Fallback lookup via Admin SDK Directory API (/customers/my_customer)
CUSTOMER_JSON="$(curl -sS -H "Authorization: Bearer ${GCP_TOKEN}" \
  -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
  "https://admin.googleapis.com/admin/directory/v1/customers/my_customer" || echo '{}')"

if [[ -z "${CLOUD_IDENTITY_CUSTOMER_ID}" ]]; then
  RAW_CUST_ID="$(echo "${CUSTOMER_JSON}" | python3 -c "import sys, json; print(json.load(sys.stdin).get('id', ''))" || true)"
  if [[ -n "${RAW_CUST_ID}" ]]; then
    CLOUD_IDENTITY_CUSTOMER_ID="customers/${RAW_CUST_ID#customers/}"
  fi
fi

CUSTOMER_RAW_ID="${CLOUD_IDENTITY_CUSTOMER_ID#customers/}"

if [[ -z "${SAML_TARGET_ORG_UNIT}" && -n "${CLOUD_IDENTITY_CUSTOMER_ID}" ]]; then
  SSO_ASSIGNMENTS_JSON="$(curl -sS -H "Authorization: Bearer ${GCP_TOKEN}" \
    -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
    "https://cloudidentity.googleapis.com/v1/inboundSsoAssignments?filter=customer%3D%3D%22${CLOUD_IDENTITY_CUSTOMER_ID}%22" || echo '{}')"
  SAML_TARGET_ORG_UNIT="$(echo "${SSO_ASSIGNMENTS_JSON}" | python3 -c "
import sys, json
d = json.load(sys.stdin)
for a in d.get('inboundSsoAssignments', []):
    if a.get('ssoMode') == 'SAML_SSO' and a.get('targetOrgUnit'):
        print(a['targetOrgUnit'])
        break
else:
    if d.get('inboundSsoAssignments'):
        print(d['inboundSsoAssignments'][0].get('targetOrgUnit', ''))
" || true)"
fi

if [[ -z "${SAML_TARGET_ORG_UNIT}" ]]; then
  ROOT_OU_JSON="$(curl -sS -H "Authorization: Bearer ${GCP_TOKEN}" \
    -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
    "https://admin.googleapis.com/admin/directory/v1/customer/${CUSTOMER_RAW_ID:-my_customer}/orgunits?type=all" || echo '{}')"
  RAW_OU_ID="$(echo "${ROOT_OU_JSON}" | python3 -c "
import sys, json
d = json.load(sys.stdin)
ous = d.get('organizationUnits', [])
for ou in ous:
    if ou.get('parentOrgUnitPath') == '/' or ou.get('orgUnitPath') == '/':
        print(ou.get('orgUnitId', '').replace('id:', ''))
        break
" || true)"
  if [[ -n "${RAW_OU_ID}" ]]; then
    SAML_TARGET_ORG_UNIT="orgUnits/${RAW_OU_ID#orgUnits/}"
  fi
fi

echo "      Resolved GCP_ORG_ID                 : ${GCP_ORG_ID:-<none>}"
echo "      Resolved CLOUD_IDENTITY_CUSTOMER_ID : ${CLOUD_IDENTITY_CUSTOMER_ID:-<none>}"
echo "      Resolved Root SAML_TARGET_ORG_UNIT  : ${SAML_TARGET_ORG_UNIT:-<none>}"

# ------------------------------------------------------------------------------
# 3. Step 0B.1b: Register & Verify Corporate Domain (cymbal.com) via Site Verification API
# ------------------------------------------------------------------------------
echo "[3/6] [Step 0B.1b] Checking domain registration & verification status for '${CUSTOMER_DOMAIN}'..."
DOMAIN_JSON="$(curl -sS -H "Authorization: Bearer ${GCP_TOKEN}" \
  -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
  "https://admin.googleapis.com/admin/directory/v1/customer/${CUSTOMER_RAW_ID:-my_customer}/domains/${CUSTOMER_DOMAIN}" || echo '{}')"

IS_VERIFIED="$(echo "${DOMAIN_JSON}" | python3 -c "import sys, json; print(str(json.load(sys.stdin).get('verified', False)).lower())" || echo "false")"
DOMAIN_EXISTS="$(echo "${DOMAIN_JSON}" | python3 -c "import sys, json; print('true' if json.load(sys.stdin).get('domainName') else 'false')" || echo "false")"

GOOGLE_VERIFICATION_TOKEN=""

if [[ "${DOMAIN_EXISTS}" != "true" ]]; then
  echo "      Registering domain '${CUSTOMER_DOMAIN}' in Google Admin Directory..."
  curl -sS -X POST "https://admin.googleapis.com/admin/directory/v1/customer/${CUSTOMER_RAW_ID:-my_customer}/domains" \
    -H "Authorization: Bearer ${GCP_TOKEN}" \
    -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
    -H "Content-Type: application/json" \
    -d "{\"domainName\": \"${CUSTOMER_DOMAIN}\"}" >/dev/null || true
fi

if [[ "${IS_VERIFIED}" == "true" ]]; then
  echo "      [OK] Domain '${CUSTOMER_DOMAIN}' is already verified in Google Admin Console."
else
  echo "      Requesting DNS_TXT verification token from Google Site Verification API..."
  TOKEN_RESP="$(curl -sS -X POST "https://www.googleapis.com/siteVerification/v1/token" \
    -H "Authorization: Bearer ${GCP_TOKEN}" \
    -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
    -H "Content-Type: application/json" \
    -d "{
      \"site\": {\"type\": \"INET_DOMAIN\", \"identifier\": \"${CUSTOMER_DOMAIN}\"},
      \"verificationMethod\": \"DNS_TXT\"
    }" || echo '{}')"

  GOOGLE_VERIFICATION_TOKEN="$(echo "${TOKEN_RESP}" | python3 -c "import sys, json; print(json.load(sys.stdin).get('token', ''))" || true)"
  echo "      Obtained TXT Verification Token: ${GOOGLE_VERIFICATION_TOKEN:-<none>}"

  if [[ -n "${DNS_ZONE_NAME}" ]]; then
    if ! gcloud dns managed-zones describe "${DNS_ZONE_NAME}" --project="${DNS_PROJECT_ID}" --quiet >/dev/null 2>&1; then
      echo "      [INFO] Cloud DNS zone '${DNS_ZONE_NAME}' not found in project '${DNS_PROJECT_ID}'; setting MANAGE_DNS_VERIFICATION_RECORD=false."
      DNS_ZONE_NAME=""
    fi
  fi

  if [[ -n "${DNS_ZONE_NAME}" && -n "${GOOGLE_VERIFICATION_TOKEN}" ]]; then
    echo "      Provisioning TXT record in Cloud DNS zone '${DNS_ZONE_NAME}' (${DNS_PROJECT_ID})..."
    gcloud dns record-sets create "${CUSTOMER_DOMAIN}." \
      --project="${DNS_PROJECT_ID}" \
      --zone="${DNS_ZONE_NAME}" \
      --type="TXT" \
      --ttl="60" \
      --rrdatas="\"${GOOGLE_VERIFICATION_TOKEN}\"" 2>/dev/null || \
    gcloud dns record-sets update "${CUSTOMER_DOMAIN}." \
      --project="${DNS_PROJECT_ID}" \
      --zone="${DNS_ZONE_NAME}" \
      --type="TXT" \
      --ttl="60" \
      --rrdatas="\"${GOOGLE_VERIFICATION_TOKEN}\""
  fi

  echo "      Triggering automated domain verification via Google Site Verification API..."
  VERIFY_RESP="$(curl -sS -X POST "https://www.googleapis.com/siteVerification/v1/webResource?verificationMethod=DNS_TXT" \
    -H "Authorization: Bearer ${GCP_TOKEN}" \
    -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
    -H "Content-Type: application/json" \
    -d "{
      \"site\": {\"type\": \"INET_DOMAIN\", \"identifier\": \"${CUSTOMER_DOMAIN}\"}
    }" || echo '{}')"
  echo "      Site Verification Response: $(echo "${VERIFY_RESP}" | tr -d '\n')"
fi

# ------------------------------------------------------------------------------
# 4. Step 0B.2: Verify Admin API Access (Directory & Cloud Identity Groups API)
# ------------------------------------------------------------------------------
echo "[4/6] [Step 0B.2] Verifying Admin SDK & Cloud Identity Groups API readiness..."
GROUPS_CHECK_HTTP="$(curl -sS -o /dev/null -w "%{http_code}" \
  -H "Authorization: Bearer ${GCP_TOKEN}" \
  -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
  "https://cloudidentity.googleapis.com/v1/groups?parent=${CLOUD_IDENTITY_CUSTOMER_ID}")"

if [[ "${GROUPS_CHECK_HTTP}" == "200" ]]; then
  echo "      [OK] Cloud Identity Groups API is enabled and responding (HTTP 200)."
else
  echo "      [WARN] Cloud Identity Groups API returned HTTP ${GROUPS_CHECK_HTTP}. Ensure 'Enable API access' is checked in admin.google.com -> Security -> API controls."
fi

# ------------------------------------------------------------------------------
# 5. Step 0B.2: Configure Inbound SAML SSO Profile & Assign to Root Org Unit
# ------------------------------------------------------------------------------
SAML_SP_ENTITY_ID=""
SAML_SP_ACS_URL=""
if [[ -n "${ENTRA_TENANT_ID}" && -n "${CLOUD_IDENTITY_CUSTOMER_ID}" ]]; then
  echo "[5/6] [Step 0B.2] Ensuring Cloud Identity Inbound SAML SSO Profile & Org Unit Assignment..."
  LIST_SSO_RESP="$(curl -sS -H "Authorization: Bearer ${GCP_TOKEN}" \
    -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
    "https://cloudidentity.googleapis.com/v1/inboundSamlSsoProfiles?filter=customer%3D%3D%22${CLOUD_IDENTITY_CUSTOMER_ID}%22" || echo '{}')"

  SAML_PROFILE_NAME="$(echo "${LIST_SSO_RESP}" | python3 -c "
import sys, json
data = json.load(sys.stdin)
for p in data.get('inboundSamlSsoProfiles', []):
    if p.get('displayName') == '${SAML_PROFILE_DISPLAY_NAME}':
        print(p.get('name', ''))
        break
" || true)"

  if [[ -z "${SAML_PROFILE_NAME}" ]]; then
    CREATE_SSO_RESP="$(curl -sS -X POST "https://cloudidentity.googleapis.com/v1/inboundSamlSsoProfiles" \
      -H "Authorization: Bearer ${GCP_TOKEN}" \
      -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
      -H "Content-Type: application/json" \
      -d "{
        \"customer\": \"${CLOUD_IDENTITY_CUSTOMER_ID}\",
        \"displayName\": \"${SAML_PROFILE_DISPLAY_NAME}\",
        \"idpConfig\": {
          \"entityId\": \"https://sts.windows.net/${ENTRA_TENANT_ID}/\",
          \"singleSignOnServiceUri\": \"https://login.microsoftonline.com/${ENTRA_TENANT_ID}/saml2\"
        }
      }" || echo '{}')"
    SAML_PROFILE_NAME="$(echo "${CREATE_SSO_RESP}" | python3 -c "import sys, json; d=json.load(sys.stdin); print(d.get('response', d).get('name', ''))" || true)"
    SAML_SP_ENTITY_ID="$(echo "${CREATE_SSO_RESP}" | python3 -c "import sys, json; d=json.load(sys.stdin); print(d.get('response', d).get('spConfig', {}).get('entityId', ''))" || true)"
    SAML_SP_ACS_URL="$(echo "${CREATE_SSO_RESP}" | python3 -c "import sys, json; d=json.load(sys.stdin); print(d.get('response', d).get('spConfig', {}).get('assertionConsumerServiceUri', ''))" || true)"
  else
    GET_SSO_RESP="$(curl -sS -H "Authorization: Bearer ${GCP_TOKEN}" \
      -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
      "https://cloudidentity.googleapis.com/v1/${SAML_PROFILE_NAME}" || echo '{}')"
    SAML_SP_ENTITY_ID="$(echo "${GET_SSO_RESP}" | python3 -c "import sys, json; d=json.load(sys.stdin); print(d.get('spConfig', {}).get('entityId', ''))" || true)"
    SAML_SP_ACS_URL="$(echo "${GET_SSO_RESP}" | python3 -c "import sys, json; d=json.load(sys.stdin); print(d.get('spConfig', {}).get('assertionConsumerServiceUri', ''))" || true)"
  fi

  if [[ -n "${SAML_PROFILE_NAME}" && -f "${SAML_CERT_FILE}" ]]; then
    echo "      Uploading Entra X.509 Certificate (${SAML_CERT_FILE}) to '${SAML_PROFILE_NAME}'..."
    PEM_PAYLOAD="$(python3 - "${SAML_CERT_FILE}" <<'PYEOF'
import json, sys
with open(sys.argv[1], "r", encoding="utf-8") as f:
    raw = f.read().strip()
if "BEGIN CERTIFICATE" not in raw:
    raw = f"-----BEGIN CERTIFICATE-----\n{raw}\n-----END CERTIFICATE-----"
print(json.dumps({"pemData": raw}))
PYEOF
    )"
    curl -sS -X POST "https://cloudidentity.googleapis.com/v1/${SAML_PROFILE_NAME}/idpCredentials:add" \
      -H "Authorization: Bearer ${GCP_TOKEN}" \
      -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
      -H "Content-Type: application/json" \
      -d "${PEM_PAYLOAD}" >/dev/null || true
  fi

  if [[ -n "${SAML_PROFILE_NAME}" && -n "${SAML_TARGET_ORG_UNIT}" ]]; then
    echo "      Assigning SAML SSO Profile '${SAML_PROFILE_NAME}' to Root Org Unit '${SAML_TARGET_ORG_UNIT}'..."
    curl -sS -X POST "https://cloudidentity.googleapis.com/v1/inboundSsoAssignments" \
      -H "Authorization: Bearer ${GCP_TOKEN}" \
      -H "x-goog-user-project: ${GCP_PROJECT_ID}" \
      -H "Content-Type: application/json" \
      -d "{
        \"customer\": \"${CLOUD_IDENTITY_CUSTOMER_ID}\",
        \"targetOrgUnit\": \"${SAML_TARGET_ORG_UNIT}\",
        \"ssoMode\": \"SAML_SSO\",
        \"samlSsoInfo\": {\"inboundSamlSsoProfile\": \"${SAML_PROFILE_NAME}\"}
      }" >/dev/null || true
  fi
else
  echo "[5/6] [Step 0B.2] Skipping SAML Profile creation (pass --entra-tenant-id to pre-create SAML SSO profile)."
fi

# ------------------------------------------------------------------------------
# 6. Auto-Generate configs/<customer>-identity.env for Phase 1
# ------------------------------------------------------------------------------
ENTRA_MS_TXT_ID=""
if [[ -n "${DNS_ZONE_NAME}" ]]; then
  if ! gcloud dns managed-zones describe "${DNS_ZONE_NAME}" --project="${DNS_PROJECT_ID}" --quiet >/dev/null 2>&1; then
    DNS_ZONE_NAME=""
  else
    EXISTING_TXT_JSON="$(gcloud dns record-sets describe "${CUSTOMER_DOMAIN}." --type=TXT --zone="${DNS_ZONE_NAME}" --project="${DNS_PROJECT_ID}" --format=json 2>/dev/null || echo '{}')"
    ENTRA_MS_TXT_ID="$(echo "${EXISTING_TXT_JSON}" | python3 -c "
import sys, json
d = json.load(sys.stdin)
for r in d.get('rrdatas', []):
    clean = r.strip('\"')
    if clean.startswith('MS='):
        print(clean)
        break
" || true)"
    if [[ -z "${GOOGLE_VERIFICATION_TOKEN}" ]]; then
      GOOGLE_VERIFICATION_TOKEN="$(echo "${EXISTING_TXT_JSON}" | python3 -c "
import sys, json
d = json.load(sys.stdin)
for r in d.get('rrdatas', []):
    clean = r.strip('\"')
    if clean.startswith('google-site-verification='):
        print(clean)
        break
" || true)"
    fi
  fi
